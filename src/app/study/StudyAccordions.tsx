'use client';

import { useState } from 'react';
import { ChevronDown, ChevronUp, Shield, BookOpen, Sparkles, Bot } from 'lucide-react';

interface StudyAccordionsProps {
  himConnection: string;
  context: string;
  wordStudy: {
    originalWord: string;
    transliteration: string;
    meaning: string;
    breakdown: string;
  };
}

export function StudyAccordions({ himConnection, context, wordStudy }: StudyAccordionsProps) {
  const [showHim, setShowHim] = useState(false);
  const [showContext, setShowContext] = useState(false);
  const [showWord, setShowWord] = useState(false);

  return (
    <div className="space-y-3">
      {/* HIM Connection */}
      <div className="bg-white rounded-xl border border-gray-200 shadow-sm overflow-hidden">
        <button
          onClick={() => setShowHim(!showHim)}
          className="w-full p-4 flex justify-between items-center text-left hover:bg-gray-50 transition-colors"
        >
          <div className="flex items-center gap-2">
            <Shield size={16} className="text-gray-500" />
            <span className="font-black text-base md:text-lg text-gray-900">HIM Connection</span>
          </div>
          {showHim ? <ChevronUp size={18} /> : <ChevronDown size={18} />}
        </button>
        {showHim && (
          <div className="p-4 pt-0 border-t border-gray-100 space-y-4">
            <p className="text-base md:text-lg text-gray-700 leading-relaxed">{himConnection}</p>
            <div className="flex items-center gap-1.5 text-[10px] text-gray-400 italic pt-3 border-t border-gray-100">
              <Bot size={12} className="shrink-0" />
              <span>Devotional content generated by AI. The best reference for the Bible is the Bible.</span>
            </div>
          </div>
        )}
      </div>

      {/* Biblical Context */}
      <div className="bg-white rounded-xl border border-gray-200 shadow-sm overflow-hidden">
        <button
          onClick={() => setShowContext(!showContext)}
          className="w-full p-4 flex justify-between items-center text-left hover:bg-gray-50 transition-colors"
        >
          <div className="flex items-center gap-2">
            <BookOpen size={16} className="text-gray-500" />
            <span className="font-black text-base md:text-lg text-gray-900">Biblical Context</span>
          </div>
          {showContext ? <ChevronUp size={18} /> : <ChevronDown size={18} />}
        </button>
        {showContext && (
          <div className="p-4 pt-0 border-t border-gray-100 space-y-4">
            <p className="text-base md:text-lg text-gray-700 leading-relaxed">{context}</p>
            <div className="flex items-center gap-1.5 text-[10px] text-gray-400 italic pt-3 border-t border-gray-100">
              <Bot size={12} className="shrink-0" />
              <span>Devotional content generated by AI. The best reference for the Bible is the Bible.</span>
            </div>
          </div>
        )}
      </div>

      {/* Deep Word Study */}
      <div className="bg-white rounded-xl border border-gray-200 shadow-sm overflow-hidden">
        <button
          onClick={() => setShowWord(!showWord)}
          className="w-full p-4 flex justify-between items-center text-left hover:bg-gray-50 transition-colors"
        >
          <div className="flex items-center gap-2">
            <Sparkles size={16} className="text-gray-500" />
            <span className="font-black text-base md:text-lg text-gray-900">Deep Word Study</span>
          </div>
          {showWord ? <ChevronUp size={18} /> : <ChevronDown size={18} />}
        </button>
        {showWord && (
          <div className="p-4 pt-0 border-t border-gray-100 space-y-4">
            <div className="text-base md:text-lg text-gray-700 leading-relaxed space-y-3">
              <p>
                <strong>Original Word:</strong> <em className="font-serif">{wordStudy.transliteration}</em> ({wordStudy.originalWord}) – {wordStudy.meaning}
              </p>
              <p>{wordStudy.breakdown}</p>
            </div>
            <div className="flex items-center gap-1.5 text-[10px] text-gray-400 italic pt-3 border-t border-gray-100">
              <Bot size={12} className="shrink-0" />
              <span>Devotional content generated by AI. The best reference for the Bible is the Bible.</span>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}